/// JS `Math.round` — half toward **+∞** (`floor(x + 0.5)`), NOT Rust's
/// half-away-from-zero. `Math.round(-12.5) === -12`, `Math.round(-0.5) === 0`.
#[must_use]
pub fn js_round(x: f64) -> f64 {
    (x + 0.5).floor()
}

/// `r2 = (x) => Math.round(x * 100) / 100` (netmatch.js L32).
#[must_use]
pub fn r2(x: f64) -> f64 {
    js_round(x * 100.0) / 100.0
}

/// `r3 = (x) => Math.round(x * 1000) / 1000` (netmatch.js L33).
#[must_use]
pub fn r3(x: f64) -> f64 {
    js_round(x * 1000.0) / 1000.0
}

/// `Math.round` on an f32-origin value, kept as an integer-valued f64 so it
/// flows through [`num`] and prints without a decimal point.
#[must_use]
pub fn round_int(x: f32) -> f64 {
    js_round(dec(x))
}

/// Re-interpret an `f32` through its shortest decimal form, as the `f64` JS
/// would hold. JS stores every number as `f64`; the Rust sim stores actor and
/// record scalars as `f32`, so `f64::from(0.61_f32)` is `0.6100000143…` — the
/// noise digits would leak into `num` and, worse, across `r2`/`r3` half-way
/// boundaries (`r3(-0.0005_f32)` → `-0.001` instead of JS `0`). Taking the
/// shortest round-trip decimal (`"0.61"`, `"-0.0005"`) and re-parsing it as
/// `f64` reproduces the exact value the JS packer saw, so the wire bytes match
/// for *any* f32 storage. `-0` collapses to `0` here, matching JS.
#[must_use]
pub fn dec(x: f32) -> f64 {
    if x == 0.0 {
        return 0.0;
    }
    x.to_string().parse().unwrap_or(f64::from(x))
}

/// Serialise a number exactly as JS `String(n)` / `JSON.stringify` would for
/// the value ranges the game produces: integer-valued doubles print with no
/// fraction (`90`, `62`), fractional ones with the shortest round-trip digits
/// (`0.13`, `-0.12`), and `-0` collapses to `0` (`JSON.stringify(-0)` is `"0"`).
/// Rust's `{}` for `f64` already matches JS for these magnitudes (integers
/// without `.0`, shortest round-trip fractions); exponent notation only diverges
/// past ~1e21 / below ~1e-4, which the rounded payloads never reach.
#[must_use]
pub fn num(v: f64) -> String {
    if v == 0.0 {
        // catches both +0.0 and -0.0 (IEEE equality), matching JS.
        return "0".to_string();
    }
    format!("{v}")
}

/// `JSON.stringify` of a string (shared escaping; ASCII names only in practice).
#[must_use]
fn js_str(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            _ => out.push(c),
        }
    }
    out.push('"');
    out
}

/// A JSON array of already-serialised element tokens.
#[must_use]
fn arr(items: impl IntoIterator<Item = String>) -> String {
    let mut out = String::from("[");
    for (i, it) in items.into_iter().enumerate() {
        if i > 0 {
            out.push(',');
        }
        out.push_str(&it);
    }
    out.push(']');
    out
}

/// A JSON object from `(key, value-token)` pairs, in the given order (JS
/// insertion order — `serde_json`'s sorted `Map` would reorder).
#[must_use]
fn obj(pairs: &[(&str, String)]) -> String {
    let mut out = String::from("{");
    for (i, (k, v)) in pairs.iter().enumerate() {
        if i > 0 {
            out.push(',');
        }
        let _ = write!(out, "{}:{}", js_str(k), v);
    }
    out.push('}');
    out
}

// ---------------------------------------------------------------------------
// JVal — an order-preserving, token-preserving JSON value for the heterogeneous
// passthrough bags (`packEvent` objects, `recZone` arrays) that must survive
// decode→encode byte-for-byte. serde_json is used only to *parse* (its
// `visit_map` feeds entries in input order, which we keep in a `Vec`).
// ---------------------------------------------------------------------------

/// A minimal JSON value that preserves object key order and integer-vs-float
/// distinction, so a JS payload decoded into it re-serialises byte-identically.
#[derive(Debug, Clone, PartialEq)]
pub enum JVal {
    Null,
    Bool(bool),
    Num(f64),
    Str(String),
    Arr(Vec<JVal>),
    /// Object entries in insertion order.
    Obj(Vec<(String, JVal)>),
}

impl JVal {
    #[must_use]
    pub fn as_f64(&self) -> Option<f64> {
        match self {
            JVal::Num(v) => Some(*v),
            _ => None,
        }
    }
    #[must_use]
    pub fn as_str(&self) -> Option<&str> {
        match self {
            JVal::Str(s) => Some(s),
            _ => None,
        }
    }
    #[must_use]
    pub fn as_bool(&self) -> Option<bool> {
        match self {
            JVal::Bool(b) => Some(*b),
            _ => None,
        }
    }
    #[must_use]
    pub fn as_array(&self) -> Option<&[JVal]> {
        match self {
            JVal::Arr(a) => Some(a),
            _ => None,
        }
    }
    /// Field lookup by key (objects only).
    #[must_use]
    pub fn field(&self, key: &str) -> Option<&JVal> {
        match self {
            JVal::Obj(pairs) => pairs.iter().find(|(k, _)| k == key).map(|(_, v)| v),
            _ => None,
        }
    }
    /// Byte-exact JS wire serialisation (no spaces, JS number formatting).
    #[must_use]
    pub fn to_wire(&self) -> String {
        match self {
            JVal::Null => "null".to_string(),
            JVal::Bool(b) => {
                if *b {
                    "true".to_string()
                } else {
                    "false".to_string()
                }
            }
            JVal::Num(v) => num(*v),
            JVal::Str(s) => js_str(s),
            JVal::Arr(a) => arr(a.iter().map(JVal::to_wire)),
            JVal::Obj(pairs) => {
                let inner: Vec<String> = pairs
                    .iter()
                    .map(|(k, v)| format!("{}:{}", js_str(k), v.to_wire()))
                    .collect();
                format!("{{{}}}", inner.join(","))
            }
        }
    }
}

/// Parse a JS wire JSON string into a [`JVal`] (order-preserving). `None` on
/// malformed input (JS guards every parse with `try/catch`).
#[must_use]
pub fn parse_json(s: &str) -> Option<JVal> {
    serde_json::from_str::<JVal>(s).ok()
}

// -- JVal serde (for the sim-internal round-trip tests; the wire path uses
//    to_wire()/parse_json so serde number formatting never reaches the socket).

impl Serialize for JVal {
    fn serialize<S: Serializer>(&self, ser: S) -> Result<S::Ok, S::Error> {
        use serde::ser::{SerializeMap, SerializeSeq};
        match self {
            JVal::Null => ser.serialize_unit(),
            JVal::Bool(b) => ser.serialize_bool(*b),
            JVal::Num(v) => ser.serialize_f64(*v),
            JVal::Str(s) => ser.serialize_str(s),
            JVal::Arr(a) => {
                let mut seq = ser.serialize_seq(Some(a.len()))?;
                for e in a {
                    seq.serialize_element(e)?;
                }
                seq.end()
            }
            JVal::Obj(pairs) => {
                let mut map = ser.serialize_map(Some(pairs.len()))?;
                for (k, v) in pairs {
                    map.serialize_entry(k, v)?;
                }
                map.end()
            }
        }
    }
}

impl<'de> Deserialize<'de> for JVal {
    fn deserialize<D: Deserializer<'de>>(de: D) -> Result<Self, D::Error> {
        struct V;
        impl<'de> Visitor<'de> for V {
            type Value = JVal;
            fn expecting(&self, f: &mut std::fmt::Formatter) -> std::fmt::Result {
                f.write_str("a JSON value")
            }
            fn visit_unit<E: de::Error>(self) -> Result<JVal, E> {
                Ok(JVal::Null)
            }
            fn visit_none<E: de::Error>(self) -> Result<JVal, E> {
                Ok(JVal::Null)
            }
            fn visit_some<D: Deserializer<'de>>(self, de: D) -> Result<JVal, D::Error> {
                de.deserialize_any(V)
            }
            fn visit_bool<E: de::Error>(self, b: bool) -> Result<JVal, E> {
                Ok(JVal::Bool(b))
            }
            fn visit_i64<E: de::Error>(self, v: i64) -> Result<JVal, E> {
                Ok(JVal::Num(v as f64))
            }
            fn visit_u64<E: de::Error>(self, v: u64) -> Result<JVal, E> {
                Ok(JVal::Num(v as f64))
            }
            fn visit_f64<E: de::Error>(self, v: f64) -> Result<JVal, E> {
                Ok(JVal::Num(v))
            }
            fn visit_str<E: de::Error>(self, v: &str) -> Result<JVal, E> {
                Ok(JVal::Str(v.to_string()))
            }
            fn visit_seq<A: SeqAccess<'de>>(self, mut seq: A) -> Result<JVal, A::Error> {
                let mut out = Vec::new();
                while let Some(e) = seq.next_element()? {
                    out.push(e);
                }
                Ok(JVal::Arr(out))
            }
            fn visit_map<A: MapAccess<'de>>(self, mut map: A) -> Result<JVal, A::Error> {
                let mut out = Vec::new();
                while let Some((k, v)) = map.next_entry::<String, JVal>()? {
                    out.push((k, v));
                }
                Ok(JVal::Obj(out))
            }
        }
        de.deserialize_any(V)
    }
}

