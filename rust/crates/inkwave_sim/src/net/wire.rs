/// Encode one [`ActorSample`] as the 24-slot `packActor` array — the exact slot
/// order and quantisation of netmatch.js L747-750. Slot 0 is the `nid` (passed
/// separately, as `packActor` reads it off the actor).
#[must_use]
pub fn pack_actor(nid: u8, s: &ActorSample) -> String {
    arr([
        num(f64::from(nid)),
        num(r2(dec(s.x))),
        num(r2(dec(s.y))),
        num(r2(dec(s.z))),
        num(r2(dec(s.vx))),
        num(r2(dec(s.vy))),
        num(r2(dec(s.vz))),
        num(r3(dec(s.yaw))),
        num(r3(dec(s.aim_yaw))),
        num(r3(dec(s.aim_pitch))),
        num(f64::from(s.f)),
        num(round_int(s.hp)),
        num(round_int(s.ink)),
        num(round_int(s.sp)),
        num(r2(dec(s.ch))),
        num(round_int(s.turf)),
        num(f64::from(s.tp)),
        num(r2(dec(s.wx))),
        num(r2(dec(s.wy))),
        num(r2(dec(s.wz))),
        num(r2(dec(s.lock))),
        num(f64::from(s.ks)),
        num(dec(s.spx)),
        num(f64::from(s.spst)),
    ])
}

/// `unpackActor(s, ts)` — decode a `packActor` array back to an
/// [`ActorSample`] (netmatch.js L753-755). The `t` field is the *tick's*
/// timestamp (`ts`), not an array slot. The `|| 0` guards on `ks`/`spx`/`spst`
/// match JS (missing/`0` ⇒ `0`).
#[must_use]
pub fn unpack_actor(a: &[JVal], ts: f32) -> ActorSample {
    let g = |i: usize| a.get(i).and_then(JVal::as_f64).unwrap_or(0.0) as f32;
    let gi = |i: usize| a.get(i).and_then(JVal::as_f64).unwrap_or(0.0) as u32;
    ActorSample {
        t: ts,
        x: g(1),
        y: g(2),
        z: g(3),
        vx: g(4),
        vy: g(5),
        vz: g(6),
        yaw: g(7),
        aim_yaw: g(8),
        aim_pitch: g(9),
        f: gi(10),
        hp: g(11),
        ink: g(12),
        sp: g(13),
        ch: g(14),
        turf: g(15),
        tp: gi(16),
        wx: g(17),
        wy: g(18),
        wz: g(19),
        lock: g(20),
        ks: gi(21),
        spx: g(22),
        spst: gi(23),
    }
}

