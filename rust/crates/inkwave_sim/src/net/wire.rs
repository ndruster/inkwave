/// Encode a point-to-point [`DirectMsg`] to its `{k:…}` JSON object. Damage is
/// already `r2`'d by the caller (sendHit L165), so it prints as-is.
#[must_use]
pub fn encode_direct(m: &DirectMsg) -> String {
    match m {
        // {k:'hit', v, a, d, w} (L165). `w` omitted when None.
        DirectMsg::Hit { v, a, d, w } => {
            let mut pairs = vec![
                ("k", js_str("hit")),
                ("v", num(f64::from(*v))),
                ("a", num(f64::from(*a))),
                ("d", num(dec(*d))),
            ];
            if let Some(w) = w {
                pairs.push(("w", js_str(w)));
            }
            obj(&pairs)
        }
        // {k:'dh', kind, id, d} (L159)
        DirectMsg::DeviceHit { kind, id, d } => obj(&[
            ("k", js_str("dh")),
            ("kind", js_str(kind)),
            ("id", num(f64::from(*id))),
            ("d", num(dec(*d))),
        ]),
        // {k:'bhit', a, d, weak, w, c} (L153); weak is 1/0, c is -1 for boss.
        DirectMsg::BossHit { a, d, weak, w, c } => obj(&[
            ("k", js_str("bhit")),
            ("a", num(f64::from(*a))),
            ("d", num(dec(*d))),
            (
                "weak",
                if *weak {
                    "1".to_string()
                } else {
                    "0".to_string()
                },
            ),
            ("w", js_str(w)),
            ("c", num(f64::from(*c))),
        ]),
    }
}

/// Decode a `d.k`-tagged object into a [`DirectMsg`] (`None` for non-direct
/// keys so the caller falls through to host/tick handling).
#[must_use]
pub fn decode_direct(v: &JVal) -> Option<DirectMsg> {
    let k = v.field("k").and_then(JVal::as_str)?;
    let f = |key: &str| v.field(key).and_then(JVal::as_f64).unwrap_or(0.0);
    match k {
        "hit" => Some(DirectMsg::Hit {
            v: f("v") as u8,
            a: f("a") as u8,
            d: f("d") as f32,
            w: v.field("w").and_then(JVal::as_str).map(str::to_string),
        }),
        "dh" => Some(DirectMsg::DeviceHit {
            kind: v.field("kind").and_then(JVal::as_str)?.to_string(),
            id: f("id") as u32,
            d: f("d") as f32,
        }),
        "bhit" => Some(DirectMsg::BossHit {
            a: f("a") as u8,
            d: f("d") as f32,
            weak: f("weak") != 0.0,
            w: v.field("w").and_then(JVal::as_str)?.to_string(),
            c: f("c") as i8,
        }),
        _ => None,
    }
}

