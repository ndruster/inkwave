/// `Transport.broadcast` — `"b|" + JSON.stringify(obj)`.
#[must_use]
pub fn envelope_broadcast(payload_json: &str) -> String {
    format!("b|{payload_json}")
}

/// `Transport.sendTo` — `"s|" + to + "|" + JSON.stringify(obj)`.
#[must_use]
pub fn envelope_send_to(to: &str, payload_json: &str) -> String {
    format!("s|{to}|{payload_json}")
}

/// Parse an inbound relay frame. Returns:
/// - `Some((Some(from), json))` for a relayed `"m|<from>|<json>"` game payload
///   (transport.js L56-60);
/// - `Some((None, json))` for a bare JSON control frame (welcome/join/…);
/// - `None` for `"ping"`/`"pong"` (answered by the runtime) or unparseable input.
#[must_use]
pub fn parse_envelope(s: &str) -> Option<(Option<String>, String)> {
    if let Some(rest) = s.strip_prefix("m|") {
        let k = rest.find('|')?;
        let from = rest[..k].to_string();
        return Some((Some(from), rest[k + 1..].to_string()));
    }
    if s == "ping" || s == "pong" {
        return None;
    }
    if s.starts_with('{') {
        return Some((None, s.to_string()));
    }
    None
}

/// Parse a relayed `"m|<from>|<json>"` frame into `(from, JVal)`.
#[must_use]
pub fn parse_relayed(s: &str) -> Option<(String, JVal)> {
    let (from, json) = parse_envelope(s)?;
    let from = from?;
    Some((from, parse_json(&json)?))
}

