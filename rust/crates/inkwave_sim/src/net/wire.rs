/// Encode one event record (`['s'|'p'|'b'|'tr'|'ev'|'k'|'z', …]`) to its wire
/// array — WITHOUT the `_rec` timestamp prefix (see [`encode_timed_event`] for
/// the prefixed form that goes in `Tick::events`).
#[must_use]
pub fn encode_record(e: &TickEvent) -> String {
    match e {
        // ['s', x, y, z, radius, team, seed, kind, sx, sy, sz, amt] (L112-113)
        TickEvent::Splat(s) => arr([
            js_str("s"),
            num(r2(dec(s.x))),
            num(r2(dec(s.y))),
            num(r2(dec(s.z))),
            num(r2(dec(s.radius))),
            num(f64::from(s.team)),
            num(r3(dec(s.seed))),
            match &s.kind {
                Some(k) => js_str(k),
                None => "0".to_string(), // `o.kind ?? 0`
            },
            num(r3(dec(s.stretch[0]))),
            num(r3(dec(s.stretch[1]))),
            num(r3(dec(s.stretch[2]))),
            num(r2(dec(s.stretch_amt))),
        ]),
        // ['p', nid, type, wid, pos(3), vel(3), delay, life, straight, radius,
        //  size, grav, drag, trailEvery, head, vis, tail0, tailK, wob, wobF,
        //  nose, sats] (L119-121) — 26 slots.
        TickEvent::Proj(p) => arr([
            js_str("p"),
            num(f64::from(p.nid)),
            js_str(&p.ptype),
            match &p.wid {
                Some(w) => js_str(w),
                None => "0".to_string(), // `p.wid || 0`
            },
            num(r2(dec(p.pos[0]))),
            num(r2(dec(p.pos[1]))),
            num(r2(dec(p.pos[2]))),
            num(r2(dec(p.vel[0]))),
            num(r2(dec(p.vel[1]))),
            num(r2(dec(p.vel[2]))),
            num(r3(dec(p.delay))),
            num(r3(dec(p.life))),
            num(r3(dec(p.straight))),
            num(r2(dec(p.radius))),
            num(r2(dec(p.size))),
            num(dec(p.grav)),
            num(dec(p.drag)),
            num(dec(p.trail_every)),
            if p.head {
                "1".to_string()
            } else {
                "0".to_string()
            }, // `p.head ? 1 : 0`
            num(r3(dec(p.vis))),
            num(dec(p.tail0)),
            num(dec(p.tail_k)),
            num(dec(p.wob)),
            num(dec(p.wob_f)),
            num(dec(p.nose)),
            num(dec(p.sats)),
        ]),
        // ['b', nid, kind, pos(3), vel(3)] (L127)
        TickEvent::Bomb(b) => arr([
            js_str("b"),
            num(f64::from(b.nid)),
            js_str(&b.kind),
            num(r2(dec(b.pos[0]))),
            num(r2(dec(b.pos[1]))),
            num(r2(dec(b.pos[2]))),
            num(r2(dec(b.vel[0]))),
            num(r2(dec(b.vel[1]))),
            num(r2(dec(b.vel[2]))),
        ]),
        // ['tr', nid, name, packTrig(data)] (L92)
        TickEvent::Trigger(t) => arr([
            js_str("tr"),
            num(f64::from(t.nid)),
            js_str(&t.name),
            pack_trig(&t.data),
        ]),
        // ['ev', name, packed] (L142) — payload carried verbatim.
        TickEvent::Event(ev) => arr([
            js_str("ev"),
            js_str(ev.name.js_wire_name()),
            ev.payload.to_wire(),
        ]),
        // ['k', nid, kind, data] (L136). The subs payload is the one mixed
        // array: JS writes the sub kind *string* at `data[2]`
        // (`[op, gid, kind, …]`, subs.js L77/L103), so the wire mirrors it.
        TickEvent::Kit(k) => {
            let data = arr(k.data.iter().enumerate().map(|(i, d)| match (i, d) {
                (2, KitVal::Num(_)) if k.kind == "subs" && k.sub_kind.is_some() => {
                    js_str(k.sub_kind.as_deref().unwrap_or_default())
                }
                (_, KitVal::Num(v)) => num(dec(*v)),
                (_, KitVal::Str(s)) => js_str(s),
            }));
            arr([js_str("k"), num(f64::from(k.nid)), js_str(&k.kind), data])
        }
        // ['z', e] (L148) — e carried verbatim.
        TickEvent::Zone(z) => arr([js_str("z"), z.payload.to_wire()]),
        // ['bm', rec] — recBoss (bossBrain.js L294); the move record object
        // passes through VERBATIM (netmatch.js L494 reads e[2] as-is), so the
        // JVal clone preserves `{id, t0, s, d, p}` field order on the wire.
        TickEvent::BossMove(rec) => arr([js_str("bm"), rec.to_wire()]),
        // ['bc', id, x, y, z, killed?1:0] — boss.js L386.
        TickEvent::BossCrabBurst {
            id,
            x,
            y,
            z,
            killed,
        } => arr([
            js_str("bc"),
            num(f64::from(*id)),
            num(r2(dec(*x))),
            num(r2(dec(*y))),
            num(r2(dec(*z))),
            if *killed {
                "1".to_string()
            } else {
                "0".to_string()
            },
        ]),
    }
}

/// `[r3(now()), ...record]` — a record on the timeline carries its sender-clock
/// timestamp FIRST (`_rec`, netmatch.js L107).
#[must_use]
pub fn encode_timed_event(e: &TimedEvent) -> String {
    let body = encode_record(&e.kind);
    // every record array starts with `["` (the tag string); keep it and splice
    // the timestamp in front.
    format!("[{},{}", num(r3(dec(e.ts))), &body[1..])
}

/// Decode a bare (untimestamped) event record array.
#[must_use]
pub fn decode_record(a: &[JVal]) -> Option<TickEvent> {
    let tag = a.first()?.as_str()?;
    let g = |i: usize| a.get(i).and_then(JVal::as_f64).unwrap_or(0.0) as f32;
    let gs = |i: usize| a.get(i).and_then(JVal::as_str).map(str::to_string);
    match tag {
        "s" => Some(TickEvent::Splat(SplatRecord {
            x: g(1),
            y: g(2),
            z: g(3),
            radius: g(4),
            team: g(5) as u8,
            seed: g(6),
            kind: gs(7), // JS `0` ⇒ None (inferred on replay)
            stretch: [g(8), g(9), g(10)],
            stretch_amt: g(11),
        })),
        "p" => Some(TickEvent::Proj(ProjectileRecord {
            nid: g(1) as u8,
            ptype: gs(2).unwrap_or_default(),
            wid: gs(3), // JS `0` ⇒ None
            pos: [g(4), g(5), g(6)],
            vel: [g(7), g(8), g(9)],
            delay: g(10),
            life: g(11),
            straight: g(12),
            radius: g(13),
            size: g(14),
            grav: g(15),
            drag: g(16),
            trail_every: g(17),
            head: g(18) != 0.0,
            vis: g(19),
            tail0: g(20),
            tail_k: g(21),
            wob: g(22),
            wob_f: g(23),
            nose: g(24),
            sats: g(25),
        })),
        "b" => Some(TickEvent::Bomb(BombRecord {
            nid: g(1) as u8,
            kind: gs(2).unwrap_or_default(),
            pos: [g(3), g(4), g(5)],
            vel: [g(6), g(7), g(8)],
        })),
        "tr" => Some(TickEvent::Trigger(TriggerRecord {
            nid: g(1) as u8,
            name: gs(2).unwrap_or_default(),
            data: unpack_trig(a.get(3)?),
        })),
        "ev" => Some(TickEvent::Event(EventRecord {
            name: ForwardEvent::from_js_name(a.get(1)?.as_str()?)?,
            payload: a.get(2).cloned().unwrap_or(JVal::Null),
        })),
        "k" => {
            let data_arr = a.get(3).and_then(JVal::as_array);
            let kind = gs(2).unwrap_or_default();
            let mut data: Vec<KitVal> = data_arr
                .map(|d| {
                    d.iter()
                        .map(|v| match v.as_str() {
                            Some(s) => KitVal::Str(s.to_string()),
                            None => KitVal::Num(v.as_f64().unwrap_or(0.0) as f32),
                        })
                        .collect()
                })
                .unwrap_or_default();
            // The subs record is a mixed array (subs.js L77/L103): the kind
            // string rides `data[2]`; it is lifted into `sub_kind` and the
            // slot keeps a `Num(0.0)` placeholder (JS index layout intact).
            // Only for `subs` — the `sp` channel's strings are payload data.
            let sub_kind = if kind == "subs" {
                match data.get_mut(2) {
                    Some(KitVal::Str(s)) => Some(std::mem::take(s)),
                    _ => None,
                }
            } else {
                None
            };
            if sub_kind.is_some() {
                data[2] = KitVal::Num(0.0);
            }
            Some(TickEvent::Kit(KitRecord {
                nid: g(1) as u8,
                kind,
                sub_kind,
                data,
            }))
        }
        "z" => Some(TickEvent::Zone(ZoneRecord {
            payload: a.get(1).cloned().unwrap_or(JVal::Null),
        })),
        // Task 41 (TR-41.2): boss records. Wrong-arity shapes decode to
        // `None` — the tick envelope itself survives, keeping the Task 40
        // tolerance contract. A right-arity `bc` with a non-numeric slot
        // coerces that slot to 0 via `g` (the JS packer always writes
        // numbers, so this only guards against corrupt relays).
        "bm" if a.len() == 2 => Some(TickEvent::BossMove(a[1].clone())),
        "bc" if a.len() == 6 => Some(TickEvent::BossCrabBurst {
            id: g(1) as u32,
            x: g(2),
            y: g(3),
            z: g(4),
            killed: g(5) != 0.0,
        }),
        _ => None,
    }
}

/// Decode a `[ts, ...record]` timeline entry.
#[must_use]
pub fn decode_timed_event(v: &JVal) -> Option<TimedEvent> {
    let a = v.as_array()?;
    let ts = a.first()?.as_f64()? as f32;
    let kind = decode_record(&a[1..])?;
    Some(TimedEvent { ts, kind })
}

// ---------------------------------------------------------------------------
// packTrig / unpackTrig (netmatch.js L789-800) — the deferred object branch
// ---------------------------------------------------------------------------

/// `packTrig(d)` (netmatch.js L789-794): `Zero` ⇒ bare `0`; `Num` ⇒ `r3`;
/// `Obj` ⇒ a key-ordered object of `r3`'d number fields.
#[must_use]
pub fn pack_trig(d: &TrigData) -> String {
    match d {
        TrigData::Zero => "0".to_string(),
        TrigData::Num(v) => num(r3(dec(*v))),
        TrigData::Obj(pairs) => {
            let inner: Vec<String> = pairs
                .iter()
                .map(|(k, v)| format!("{}:{}", js_str(k), num(r3(dec(*v)))))
                .collect();
            format!("{{{}}}", inner.join(","))
        }
    }
}

/// `unpackTrig(d)` (netmatch.js L796-800): falsy ⇒ `Zero`, number ⇒ `Num`,
/// object ⇒ `Obj` of its number fields (values already rounded on the wire).
#[must_use]
pub fn unpack_trig(v: &JVal) -> TrigData {
    match v {
        JVal::Null => TrigData::Zero,
        JVal::Bool(false) => TrigData::Zero,
        JVal::Num(n) => {
            if *n == 0.0 {
                TrigData::Zero
            } else {
                TrigData::Num(*n as f32)
            }
        }
        JVal::Obj(map) => {
            let mut out = Vec::new();
            for (k, val) in map {
                if let Some(f) = val.as_f64() {
                    out.push((k.clone(), f as f32));
                }
            }
            if out.is_empty() {
                TrigData::Zero
            } else {
                TrigData::Obj(out)
            }
        }
        _ => TrigData::Zero,
    }
}

