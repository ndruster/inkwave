/// Encode a host [`HostMsg`] to its `{k:…}` JSON. Turf War only: `Result`
/// omits the zones/boss extras (`mode`/`bo` are `undefined` for turf, so JS
/// drops them from `JSON.stringify`).
#[must_use]
pub fn encode_host(m: &HostMsg) -> String {
    match m {
        // {k:'st', s, t} (L80)
        HostMsg::State { phase, t } => obj(&[
            ("k", js_str("st")),
            ("s", js_str(phase)),
            ("t", num(r2(dec(*t)))),
        ]),
        // The clock rides the tick as `c`, not a standalone message — encode it
        // as the `[state, r2(time)]` array for completeness.
        HostMsg::Clock { phase, t } => encode_clock(phase, *t),
        // {k:'res', cov, win, st} (L652-654); turf form drops mode/bo.
        HostMsg::Result {
            coverage,
            winner,
            stats,
        } => {
            let cov = arr([num(dec(coverage[0])), num(dec(coverage[1]))]);
            let st = arr(stats.iter().map(|r| {
                arr([
                    num(f64::from(r.nid)),
                    num(f64::from(r.turf)),
                    num(f64::from(r.splats)),
                    num(f64::from(r.deaths)),
                    "0".to_string(), // bossDmg (M2+ ⇒ 0)
                    "0".to_string(), // weakHits (M2+ ⇒ 0)
                ])
            }));
            obj(&[
                ("k", js_str("res")),
                ("cov", cov),
                ("win", num(f64::from(*winner))),
                ("st", st),
            ])
        }
        // {k:'end'} (L666)
        HostMsg::End => obj(&[("k", js_str("end"))]),
        // {k:'own', map:{nid: owner}} — reserved stub (host never sends it).
        HostMsg::Ownership { map } => {
            let inner: Vec<String> = map
                .iter()
                .map(|(nid, owner)| format!("{}:{}", js_str(&nid.to_string()), js_str(owner)))
                .collect();
            obj(&[
                ("k", js_str("own")),
                ("map", format!("{{{}}}", inner.join(","))),
            ])
        }
    }
}

#[must_use]
pub fn decode_host(v: &JVal) -> Option<HostMsg> {
    let k = v.field("k").and_then(JVal::as_str)?;
    match k {
        "st" => Some(HostMsg::State {
            phase: v.field("s").and_then(JVal::as_str)?.to_string(),
            t: v.field("t").and_then(JVal::as_f64).unwrap_or(0.0) as f32,
        }),
        "res" => {
            let cov = v.field("cov").and_then(JVal::as_array)?;
            let stats = v
                .field("st")
                .and_then(JVal::as_array)
                .map(|rows| {
                    rows.iter()
                        .filter_map(|r| {
                            let a = r.as_array()?;
                            Some(super::ActorStatsRow {
                                nid: a.first()?.as_f64()? as u8,
                                turf: a.get(1)?.as_f64()? as i32,
                                splats: a.get(2)?.as_f64()? as u32,
                                deaths: a.get(3)?.as_f64()? as u32,
                            })
                        })
                        .collect()
                })
                .unwrap_or_default();
            Some(HostMsg::Result {
                coverage: [
                    cov.first().and_then(JVal::as_f64).unwrap_or(0.0) as f32,
                    cov.get(1).and_then(JVal::as_f64).unwrap_or(0.0) as f32,
                ],
                winner: v.field("win").and_then(JVal::as_f64).unwrap_or(0.0) as u8,
                stats,
            })
        }
        "end" => Some(HostMsg::End),
        "own" => {
            let map = v
                .field("map")
                .and_then(|m| match m {
                    JVal::Obj(pairs) => Some(pairs),
                    _ => None,
                })
                .map(|pairs| {
                    pairs
                        .iter()
                        .filter_map(|(nid, owner)| {
                            Some((nid.parse().ok()?, owner.as_str()?.to_string()))
                        })
                        .collect()
                })
                .unwrap_or_default();
            Some(HostMsg::Ownership { map })
        }
        _ => None,
    }
}

