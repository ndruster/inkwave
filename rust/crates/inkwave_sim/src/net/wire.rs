//! Task 17 — PROTO v1 **wire codec**: the byte-exact translation between the
//! lossless sim types in [`crate::net`] and the JSON the JS client / Cloudflare
//! relay put on the socket.
//!
//! # Why this is hand-rolled (not `serde_json`)
//!
//! Two JS behaviours make off-the-shelf JSON wrong on the wire:
//!
//! 1. **Number formatting.** `JSON.stringify` prints an integer-valued double
//!    with no decimal point (`90`, `62`) and a fractional one with the shortest
//!    round-trip digits (`0.13`, `-0.12`); `-0` prints as `0`. `serde_json`
//!    (ryu) instead prints `90.0` / `62.0`, which is NOT byte-identical to what
//!    the JS packers emit, and AC-M2-1 demands byte equality. [`num`] mirrors JS
//!    `String(n)` for the value ranges the game uses.
//! 2. **Rounding.** The packers call `Math.round` (JS rounds half **toward
//!    +∞**: `Math.round(-12.5) === -12`, `Math.round(0.5) === 1`), which is
//!    `floor(x + 0.5)` — NOT Rust's `f64::round` (half away from zero). [`r2`]
//!    / [`r3`] / [`js_round`] reproduce it exactly.
//!
//! Object key order on the wire follows the JS object-literal / `for..in`
//! insertion order, so every message is assembled with a fixed key sequence
//! here (and heterogeneous passthrough payloads ride [`JVal`], which preserves
//! order) rather than through a sorted `HashMap`/`Value::Object`.
//!
//! # Coverage (netmatch.js packers, server/src/index.js frames)
//!
//! - [`pack_actor`] / [`unpack_actor`] — the 24-slot array (L723-757).
//! - [`encode_tick`] / [`decode_tick`] — `{k:'t',ts,a,[e],[c]}` (L190-203).
//! - [`encode_record`] / [`decode_record`] — the `['s'|'p'|'b'|'tr'|'ev'|'k'|'z']`
//!   event records; [`pack_trig`] / [`unpack_trig`] cover packTrig's three
//!   branches (null / number / object) that net.rs deferred to this layer.
//! - [`encode_direct`] / [`decode_direct`], [`encode_host`] / [`decode_host`],
//!   [`encode_control`] / [`decode_control`] — the point-to-point, host-broadcast
//!   and relay frames.
//! - [`envelope_broadcast`] / [`envelope_send_to`] / [`parse_envelope`] — the
//!   `b|` / `s|to|` / `m|from|` transport wrappers.
//!
//! Gold-standard fixtures (`rust/assets/net-fixtures.json`, generated by
//! `rust/tools/net-fixtures/gen.mjs` from the **real** sliced JS packers) pin
//! every function below to byte-identical output; see the `tests` module.

