/// The host clock snapshot `msg.c = [state, r2(time)]` (L199).
#[must_use]
pub fn encode_clock(phase: &str, time: f32) -> String {
    arr([js_str(phase), num(r2(dec(time)))])
}

/// Encode a [`Tick`] to the `{k:'t',ts,a,[e],[c]}` object. Key order follows
/// `_sendTick`: `e` is attached before the host's `c` (L194-200), so a host tick
/// with events is `{k,ts,a,e,c}`.
#[must_use]
pub fn encode_tick(t: &Tick, clock: Option<(&str, f32)>) -> String {
    let a = arr(t.actors.iter().map(|(nid, s)| pack_actor(*nid, s)));
    let mut pairs: Vec<(&str, String)> =
        vec![("k", js_str("t")), ("ts", num(r3(dec(t.ts)))), ("a", a)];
    if !t.events.is_empty() {
        pairs.push(("e", arr(t.events.iter().map(encode_timed_event))));
    }
    if let Some((p, time)) = clock {
        pairs.push(("c", encode_clock(p, time)));
    }
    obj(&pairs)
}

/// Decode a `{k:'t',…}` object. Returns `(tick, host_clock_option)`.
#[must_use]
pub fn decode_tick(v: &JVal) -> (Tick, Option<(String, f32)>) {
    let ts = v.field("ts").and_then(JVal::as_f64).unwrap_or(0.0) as f32;
    let mut actors = Vec::new();
    if let Some(rows) = v.field("a").and_then(JVal::as_array) {
        for row in rows {
            if let Some(a) = row.as_array()
                && let Some(nid) = a.first().and_then(JVal::as_f64)
            {
                actors.push((nid as u8, unpack_actor(a, ts)));
            }
        }
    }
    let mut events = Vec::new();
    if let Some(recs) = v.field("e").and_then(JVal::as_array) {
        for rec in recs {
            if let Some(te) = decode_timed_event(rec) {
                events.push(te);
            }
        }
    }
    let clock = v.field("c").and_then(|c| {
        let arr = c.as_array()?;
        let phase = arr.first()?.as_str()?.to_string();
        let t = arr.get(1)?.as_f64()? as f32;
        Some((phase, t))
    });
    (Tick { ts, actors, events }, clock)
}

