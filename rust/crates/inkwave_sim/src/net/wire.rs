#[must_use]
pub fn encode_control(f: &ControlFrame) -> String {
    match f {
        ControlFrame::Welcome { id, host, members } => {
            let m = arr(members
                .iter()
                .map(|(id, name)| obj(&[("id", js_str(id)), ("name", js_str(name))])));
            obj(&[
                ("t", js_str("welcome")),
                ("id", js_str(id)),
                ("host", js_str(host)),
                ("members", m),
            ])
        }
        ControlFrame::Join { id, name } => obj(&[
            ("t", js_str("join")),
            ("m", obj(&[("id", js_str(id)), ("name", js_str(name))])),
        ]),
        ControlFrame::Leave { id, host } => obj(&[
            ("t", js_str("leave")),
            ("id", js_str(id)),
            ("host", js_str(host)),
        ]),
        ControlFrame::Err { e } => obj(&[("t", js_str("err")), ("e", js_str(e))]),
        ControlFrame::Pong { c } => obj(&[("t", js_str("pong")), ("c", num(*c))]),
        ControlFrame::Lock { v } => obj(&[
            ("t", js_str("lock")),
            (
                "v",
                if *v {
                    "true".to_string()
                } else {
                    "false".to_string()
                },
            ),
        ]),
    }
}

#[must_use]
pub fn decode_control(v: &JVal) -> Option<ControlFrame> {
    let t = v.field("t").and_then(JVal::as_str)?;
    match t {
        "welcome" => {
            let members = v
                .field("members")
                .and_then(JVal::as_array)
                .map(|a| {
                    a.iter()
                        .filter_map(|m| {
                            Some((
                                m.field("id")?.as_str()?.to_string(),
                                m.field("name")?.as_str()?.to_string(),
                            ))
                        })
                        .collect()
                })
                .unwrap_or_default();
            Some(ControlFrame::Welcome {
                id: v.field("id").and_then(JVal::as_str)?.to_string(),
                host: v.field("host").and_then(JVal::as_str)?.to_string(),
                members,
            })
        }
        "join" => {
            let m = v.field("m")?;
            Some(ControlFrame::Join {
                id: m.field("id").and_then(JVal::as_str)?.to_string(),
                name: m.field("name").and_then(JVal::as_str)?.to_string(),
            })
        }
        "leave" => Some(ControlFrame::Leave {
            id: v.field("id").and_then(JVal::as_str)?.to_string(),
            host: v.field("host").and_then(JVal::as_str)?.to_string(),
        }),
        "err" => Some(ControlFrame::Err {
            e: v.field("e").and_then(JVal::as_str)?.to_string(),
        }),
        "pong" => Some(ControlFrame::Pong {
            c: v.field("c").and_then(JVal::as_f64)?,
        }),
        "lock" => Some(ControlFrame::Lock {
            v: v.field("v").and_then(JVal::as_bool)?,
        }),
        _ => None,
    }
}

